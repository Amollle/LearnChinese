// Downloads the stock photos used in the app (from Unsplash) into assets/photos,
// so they are bundled inside the app and don't need to load on the phone.
// Runs automatically from "Start LearnChinese.command". Safe to run again.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const photosDir = path.join(root, 'assets', 'photos');
const dataFile = path.join(root, 'src', 'data', 'pictographs.ts');
const outFile = path.join(root, 'src', 'data', 'photoFiles.ts');

const source = fs.readFileSync(dataFile, 'utf8');
const ids = [...new Set([...source.matchAll(/photo: '([^']+)'/g)].map((m) => m[1]))];
fs.mkdirSync(photosDir, { recursive: true });

let downloaded = 0;
let failed = 0;
for (const id of ids) {
  const file = path.join(photosDir, `${id}.jpg`);
  if (fs.existsSync(file) && fs.statSync(file).size > 1000) continue;
  const url = `https://images.unsplash.com/${id}?fm=jpg&q=72&w=800&fit=crop&ixlib=rb-4.1.0`;
  try {
    const res = await fetch(url, { headers: { 'User-Agent': 'Mozilla/5.0 LearnChinese' } });
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    const buf = Buffer.from(await res.arrayBuffer());
    if (buf.length < 1000) throw new Error('file too small');
    fs.writeFileSync(file, buf);
    downloaded++;
  } catch (e) {
    failed++;
    console.log(`  Could not download photo ${id}: ${e.message}`);
  }
}

const present = ids.filter((id) => fs.existsSync(path.join(photosDir, `${id}.jpg`)));
const lines = [
  '// Generated by scripts/download-photos.mjs — photos bundled inside the app.',
  'export const photoFiles: Record<string, number> = {',
  ...present.map((id) => `  '${id}': require('../../assets/photos/${id}.jpg'),`),
  '};',
  '',
];
const next = lines.join('\n');
if (!fs.existsSync(outFile) || fs.readFileSync(outFile, 'utf8') !== next) fs.writeFileSync(outFile, next);

console.log(
  `Photos: ${present.length}/${ids.length} ready` +
    (downloaded ? ` (${downloaded} downloaded)` : '') +
    (failed ? ` — ${failed} could not be downloaded, emoji will be shown for those.` : '.'),
);
